#!/usr/bin/env node
// Builds LEDGER-INDEX.md, the short first read of the evidence ledger
// (BL-0016 F5). EVIDENCE_LEDGER.md stays the authority and the only file
// anyone edits; this is generated from it. Live records carry their status,
// proof class and statement; closed ones (superseded, stale, rejected) carry
// only their title and what replaced them.
// Does NOT carry evidence, scope, reverify or notes: open the record before
// relying on it.
//
// Usage: node tools/build-ledger-index.js [--check]

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const LEDGER = path.join(ROOT, 'EVIDENCE_LEDGER.md');
const INDEX = path.join(ROOT, 'LEDGER-INDEX.md');
const CLOSED = new Set(['superseded', 'stale', 'rejected']);

function buildIndex(text) {
  const live = [];
  const closed = [];
  for (const record of text.split(/^### (?=[A-Z]+-\d{4}\b)/m).slice(1)) {
    const heading = record.split('\n')[0].trim();
    const id = /^[A-Z]+-\d{4}/.exec(heading)[0];
    const field = (name) => ((new RegExp(`^- \\*\\*${name}:\\*\\*[ \\t]*(.*)$`, 'm').exec(record) || [])[1] || '').trim();
    const status = field('status');
    if (CLOSED.has(status)) {
      closed.push(`- **${heading}** — ${status}; replaced by ${field('superseded_by') || '[]'}`);
    } else {
      const proof = field('proof_class').split(/[;—]/)[0].trim();
      const claim = field('statement') || field('question');
      live.push(`### ${heading}\n\n**${status}** · ${proof}${field('superseded_by') && field('superseded_by') !== '[]' ? ` · corrected by ${field('superseded_by')}` : ''}\n\n${claim}\n`);
    }
  }
  return [
    '<!-- Generated by tools/build-ledger-index.js from EVIDENCE_LEDGER.md. Do not edit; the gate fails when it is stale. -->',
    '# Evidence ledger index',
    '',
    'The short first read of [EVIDENCE_LEDGER.md](EVIDENCE_LEDGER.md), which remains the authority.',
    'Each entry gives status, proof class and claim only. Before relying on a record, open it in the',
    'ledger for its scope, evidence and limits; the ledger header defines every status and proof class.',
    '',
    `## Live records (${live.length})`,
    '',
    ...live,
    `## Closed records (${closed.length})`,
    '',
    ...closed,
    '',
  ].join('\n');
}

function main() {
  const built = buildIndex(fs.readFileSync(LEDGER, 'utf8'));
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(INDEX) ? fs.readFileSync(INDEX, 'utf8') : '';
    if (current !== built) {
      console.error('LEDGER-INDEX.md is stale; run node tools/build-ledger-index.js');
      process.exitCode = 1;
    }
    return;
  }
  fs.writeFileSync(INDEX, built);
}

if (require.main === module) main();

module.exports = { buildIndex };
